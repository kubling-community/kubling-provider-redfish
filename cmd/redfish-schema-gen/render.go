package main

import (
	"bytes"
	"fmt"
	"strconv"
)

func renderCatalog(catalog generatedCatalog) ([]byte, error) {
	var output bytes.Buffer
	output.WriteString("// Code generated by redfish-schema-gen; DO NOT EDIT.\n\n")
	output.WriteString("package catalog\n\n")
	output.WriteString("import kublingv1 \"github.com/kubling-community/kubling-grpc/sdk-go/kubling/v1\"\n\n")
	output.WriteString("const (\n")
	writeQuotedAssignment(&output, "ProfileName", catalog.ProfileName)
	writeQuotedAssignment(&output, "Namespace", catalog.Namespace)
	writeQuotedAssignment(&output, "DMTFRelease", catalog.Release)
	writeQuotedAssignment(&output, "DMTFCommit", catalog.Commit)
	output.WriteString(")\n\n")
	output.WriteString("var generatedTables = []Table{\n")
	for _, table := range catalog.Tables {
		output.WriteString("{\n")
		writeQuotedField(&output, "Name", table.Name)
		writeQuotedField(&output, "Annotation", table.Annotation)
		writeQuotedField(&output, "SchemaFile", table.SchemaFile)
		writeQuotedField(&output, "SchemaDefinition", table.SchemaDefinition)
		fmt.Fprintf(&output, "Discovery: Discovery{Kind: %s, ", table.DiscoveryKind)
		if table.DiscoveryURI != "" {
			fmt.Fprintf(&output, "URI: %s", strconv.Quote(table.DiscoveryURI))
		} else if table.DiscoveryPointer != "" {
			fmt.Fprintf(&output, "JSONPointer: %s", strconv.Quote(table.DiscoveryPointer))
		} else if len(table.TraversalRoutes) != 0 {
			output.WriteString("Routes: []TraversalRoute{\n")
			for _, route := range table.TraversalRoutes {
				output.WriteString("{\n")
				fmt.Fprintf(&output, "Mode: %s,\n", route.Mode)
				writeTraversalSteps(&output, "Prefix", route.Prefix)
				output.WriteString("Branches: []TraversalBranch{\n")
				for _, branch := range route.Branches {
					output.WriteString("{\n")
					writeQuotedField(&output, "ID", branch.ID)
					if branch.Variant != "" {
						writeQuotedField(&output, "Variant", branch.Variant)
					}
					writeTraversalSteps(&output, "Steps", branch.Steps)
					output.WriteString("},\n")
				}
				output.WriteString("},\n},\n")
			}
			output.WriteString("}")
		}
		output.WriteString("},\n")
		output.WriteString("Columns: []Column{\n")
		for _, column := range table.Columns {
			output.WriteString("{\n")
			writeQuotedField(&output, "Name", column.Name)
			fmt.Fprintf(&output, "Source: %s,\n", column.SourceConstant)
			if column.Pointer != "" {
				writeQuotedField(&output, "JSONPointer", column.Pointer)
			}
			if column.Context != "" {
				writeQuotedField(&output, "ContextKey", column.Context)
			}
			fmt.Fprintf(&output, "Type: kublingv1.ValueType_%s,\n", column.TypeConstant)
			writeQuotedField(&output, "NativeType", column.NativeType)
			if column.Nullable {
				output.WriteString("Nullable: true,\n")
			}
			if column.Searchable {
				output.WriteString("EqualitySearch: true,\n")
			}
			writeQuotedField(&output, "Annotation", column.Annotation)
			if len(column.Mappings) != 0 {
				output.WriteString("Mappings: []ColumnMapping{\n")
				for _, mapping := range column.Mappings {
					output.WriteString("{\n")
					writeQuotedField(&output, "BranchID", mapping.BranchID)
					if mapping.Pointer != "" {
						writeQuotedField(&output, "JSONPointer", mapping.Pointer)
					}
					if mapping.Null {
						output.WriteString("Null: true,\n")
					}
					writePredicate(&output, mapping.PredicatePointer, mapping.PredicateEquals)
					output.WriteString("},\n")
				}
				output.WriteString("},\n")
			}
			output.WriteString("},\n")
		}
		output.WriteString("},\n")
		writeStringSlice(&output, "StableKeyColumns", table.StableKey)
		writeStringSlice(&output, "RoutingColumns", table.Routing)
		output.WriteString("},\n")
	}
	output.WriteString("}\n")
	return output.Bytes(), nil
}

func writeTraversalSteps(output *bytes.Buffer, field string, steps []generatedTraversalStep) {
	fmt.Fprintf(output, "%s: []TraversalStep{\n", field)
	for _, step := range steps {
		output.WriteString("{\n")
		fmt.Fprintf(output, "Kind: %s,\n", step.Kind)
		writeQuotedField(output, "JSONPointer", step.Pointer)
		writeQuotedField(output, "SchemaFile", step.SchemaFile)
		writeQuotedField(output, "SchemaDefinition", step.SchemaDefinition)
		if step.Capture != "" {
			writeQuotedField(output, "Capture", step.Capture)
		}
		writePredicate(output, step.PredicatePointer, step.PredicateEquals)
		output.WriteString("},\n")
	}
	output.WriteString("},\n")
}

func writePredicate(output *bytes.Buffer, pointer string, equals string) {
	if pointer == "" {
		return
	}
	fmt.Fprintf(output, "Predicate: &Predicate{JSONPointer: %s, Equals: %s},\n", strconv.Quote(pointer), strconv.Quote(equals))
}

func writeQuotedAssignment(output *bytes.Buffer, name string, value string) {
	fmt.Fprintf(output, "%s = %s\n", name, strconv.Quote(value))
}

func writeQuotedField(output *bytes.Buffer, name string, value string) {
	fmt.Fprintf(output, "%s: %s,\n", name, strconv.Quote(value))
}

func writeStringSlice(output *bytes.Buffer, name string, values []string) {
	fmt.Fprintf(output, "%s: []string{", name)
	for index, value := range values {
		if index != 0 {
			output.WriteString(", ")
		}
		output.WriteString(strconv.Quote(value))
	}
	output.WriteString("},\n")
}
