func TestGenerateIsDeterministicAndMatchesCommittedCatalog(t *testing.T) {
	root := repositoryRoot(t)
	profilePath := filepath.Join(root, defaultProfile)
	lockPath := filepath.Join(root, defaultLock)
	first, err := generate(profilePath, lockPath)
	if err != nil {
		t.Fatalf("generate(first) error = %v", err)
	}
	second, err := generate(profilePath, lockPath)
	if err != nil {
		t.Fatalf("generate(second) error = %v", err)
	}
	if !bytes.Equal(first, second) {
		t.Fatal("successive generations are not byte-identical")
	}
	current, err := os.ReadFile(filepath.Join(root, defaultOutput))
	if err != nil {
		t.Fatalf("os.ReadFile(generated catalog) error = %v", err)
	}
	if !bytes.Equal(first, current) {
		t.Fatal("committed catalog differs from generated bytes")
	}
	var stderr bytes.Buffer
	if err := run([]string{"--check", "--root", root}, &stderr); err != nil {
		t.Fatalf("run(--check) error = %v; stderr = %s", err, stderr.String())
	}
}

func TestCheckDetectsGeneratedDrift(t *testing.T) {
	root := repositoryRoot(t)
	generated, err := generate(filepath.Join(root, defaultProfile), filepath.Join(root, defaultLock))
	if err != nil {
		t.Fatalf("generate() error = %v", err)
	}
	output := filepath.Join(t.TempDir(), "catalog_gen.go")
	if err := os.WriteFile(output, append(generated, '\n'), 0o600); err != nil {
		t.Fatalf("os.WriteFile() error = %v", err)
	}
	var stderr bytes.Buffer
	err = run([]string{"--check", "--root", root, "--output", output}, &stderr)
	if err == nil || !strings.Contains(err.Error(), "is stale") {
		t.Fatalf("run(--check drift) error = %v, want stale", err)
	}
}

func TestResolverFollowsDMTFReferencesAndInfersNullability(t *testing.T) {
	root := repositoryRoot(t)
	schemas, err := loadSchemaSet(filepath.Join(root, defaultLock))
	if err != nil {
		t.Fatalf("loadSchemaSet() error = %v", err)
	}
	resolver := schemaResolver{documents: schemas.documents}
	tests := map[string]struct {
		file       string
		definition string
		pointer    string
		typeName   string
		nullable   bool
	}{
		"external and local status refs": {
			file:       "ComputerSystem.v1_29_0.json",
			definition: "ComputerSystem",
			pointer:    "/Status/Health",
			typeName:   "VALUE_TYPE_STRING",
			nullable:   true,
		},
		"required local enum": {
			file:       "Chassis.v1_29_0.json",
			definition: "Chassis",
			pointer:    "/ChassisType",
			typeName:   "VALUE_TYPE_STRING",
			nullable:   false,
		},
		"collection link through idRef": {
			file:       "ServiceRoot.v1_22_0.json",
			definition: "ServiceRoot",
			pointer:    "/Systems/@odata.id",
			typeName:   "VALUE_TYPE_STRING",
			nullable:   true,
		},
		"latest locked excerpt through versioned alias": {
			file:       "EnvironmentMetrics.v1_7_0.json",
			definition: "EnvironmentMetrics",
			pointer:    "/PowerWatts/Reading",
			typeName:   "VALUE_TYPE_DOUBLE",
			nullable:   true,
		},
	}
	for name, test := range tests {
		t.Run(name, func(t *testing.T) {
			resolved, err := resolver.resolveProperty(test.file, test.definition, test.pointer)
			if err != nil {
				t.Fatalf("resolveProperty() error = %v", err)
			}
			if resolved.logicalType != test.typeName || resolved.nullable != test.nullable {
				t.Fatalf("resolveProperty() = type %s nullable %v", resolved.logicalType, resolved.nullable)
			}
		})
	}
}

func TestCompileProfileGeneratesGraphFallbacksAndVariantMappings(t *testing.T) {
	root := repositoryRoot(t)
	input, err := loadProfile(filepath.Join(root, defaultProfile))
	if err != nil {
		t.Fatalf("loadProfile() error = %v", err)
	}
	schemas, err := loadSchemaSet(filepath.Join(root, defaultLock))
	if err != nil {
		t.Fatalf("loadSchemaSet() error = %v", err)
	}
	compiled, err := compileProfile(input, schemas)
	if err != nil {
		t.Fatalf("compileProfile() error = %v", err)
	}
	if len(compiled.Tables) != 22 {
		t.Fatalf("table count = %d", len(compiled.Tables))
	}
	namespaces := generatedTableByName(t, compiled, "NAMESPACES")
	if namespaces.DiscoveryKind != "DiscoveryRegistry" || namespaces.SchemaFile != "" ||
		namespaces.SchemaDefinition != "" || strings.Join(namespaces.StableKey, ",") != "namespace" ||
		len(namespaces.Routing) != 0 {
		t.Fatalf("namespace registry table = %#v", namespaces)
	}
	deviceCount := generatedColumnByName(t, namespaces, "device_count")
	if deviceCount.SourceConstant != "ColumnSourceDeviceCount" ||
		deviceCount.TypeConstant != "VALUE_TYPE_LONG" || deviceCount.Nullable {
		t.Fatalf("namespace device_count column = %#v", deviceCount)
	}
	metrics := generatedTableByName(t, compiled, "CHASSIS_ENVIRONMENT_METRICS")
	if metrics.DiscoveryKind != "DiscoveryGraph" || len(metrics.TraversalRoutes) != 1 ||
		metrics.TraversalRoutes[0].Mode != "TraversalFallback" ||
		len(metrics.TraversalRoutes[0].Branches) != 2 {
		t.Fatalf("metrics traversal = %#v", metrics.TraversalRoutes)
	}
	fans := generatedTableByName(t, compiled, "FANS")
	speed := generatedColumnByName(t, fans, "speed_rpm")
	if speed.TypeConstant != "VALUE_TYPE_DOUBLE" || !speed.Nullable || len(speed.Mappings) != 2 ||
		speed.Mappings[1].PredicatePointer != "/ReadingUnits" || speed.Mappings[1].PredicateEquals != "RPM" {
		t.Fatalf("fan speed mappings = %#v", speed)
	}
	relation := generatedTableByName(t, compiled, "SYSTEM_CHASSIS")
	if strings.Join(relation.StableKey, ",") != "namespace,device_id,source_uri,target_uri" {
		t.Fatalf("relation stable key = %v", relation.StableKey)
	}
}

