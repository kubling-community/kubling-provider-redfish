func TestLockedSubsetRejectsByteDrift(t *testing.T) {
	root := repositoryRoot(t)
	lock, err := loadLock(filepath.Join(root, defaultLock))
	if err != nil {
		t.Fatalf("loadLock() error = %v", err)
	}
	temporarySchema := filepath.Join(t.TempDir(), "schema")
	temporaryUpstream := filepath.Join(temporarySchema, "upstream")
	if err := os.MkdirAll(temporaryUpstream, 0o755); err != nil {
		t.Fatalf("os.MkdirAll() error = %v", err)
	}
	lockContents, err := os.ReadFile(filepath.Join(root, defaultLock))
	if err != nil {
		t.Fatalf("read lock error = %v", err)
	}
	temporaryLock := filepath.Join(temporarySchema, "upstream.lock.json")
	if err := os.WriteFile(temporaryLock, lockContents, 0o600); err != nil {
		t.Fatalf("write lock error = %v", err)
	}
	for _, entry := range lock.Files {
		source := filepath.Join(root, "schema", "upstream", filepath.FromSlash(entry.Path))
		target := filepath.Join(temporaryUpstream, filepath.FromSlash(entry.Path))
		copyTestFile(t, source, target)
	}
	tampered := filepath.Join(temporaryUpstream, "json-schema", "Resource.json")
	file, err := os.OpenFile(tampered, os.O_APPEND|os.O_WRONLY, 0)
	if err != nil {
		t.Fatalf("os.OpenFile() error = %v", err)
	}
	if _, err := file.WriteString("\n"); err != nil {
		_ = file.Close()
		t.Fatalf("tamper write error = %v", err)
	}
	if err := file.Close(); err != nil {
		t.Fatalf("tamper close error = %v", err)
	}
	if _, err := loadSchemaSet(temporaryLock); err == nil || !strings.Contains(err.Error(), "does not match SHA-256") {
		t.Fatalf("loadSchemaSet(tampered) error = %v, want SHA-256 mismatch", err)
	}
}

func repositoryRoot(t *testing.T) string {
	t.Helper()
	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatalf("filepath.Abs() error = %v", err)
	}
	return root
}

func copyTestFile(t *testing.T, source string, target string) {
	t.Helper()
	contents, err := os.ReadFile(source)
	if err != nil {
		t.Fatalf("read %s: %v", source, err)
	}
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		t.Fatalf("create %s: %v", filepath.Dir(target), err)
	}
	if err := os.WriteFile(target, contents, 0o600); err != nil {
		t.Fatalf("write %s: %v", target, err)
	}
}

func generatedTableByName(t *testing.T, catalog generatedCatalog, name string) generatedTable {
	t.Helper()
	for _, table := range catalog.Tables {
		if table.Name == name {
			return table
		}
	}
	t.Fatalf("generated table %s is missing", name)
	return generatedTable{}
}

func generatedColumnByName(t *testing.T, table generatedTable, name string) generatedColumn {
	t.Helper()
	for _, column := range table.Columns {
		if column.Name == name {
			return column
		}
	}
	t.Fatalf("generated column %s.%s is missing", table.Name, name)
	return generatedColumn{}
}
